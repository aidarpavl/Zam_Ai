def default_theme(p):
    return DEFAULT_THEME.get(p, DEFAULT_THEME["generic"])


def default_goal(p):
    return DEFAULT_GOAL.get(p, DEFAULT_GOAL["generic"])


def numbered(items):
    return "\n".join(f"{i + 1}. {x}" for i, x in enumerate(items))


def table_to_tsv(matrix, limit=None):
    rows = matrix if limit is None else matrix[:limit]
    return "\n".join("\t".join(to_str(v) for v in r) for r in rows)


