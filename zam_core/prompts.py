def report_docx(report_text: str, calc_table=None) -> bytes:
    """Анықтаманы Word (.docx) файлына айналдыру."""
    from docx import Document
    from docx.shared import Pt

    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(12)
    lines = report_text.split("\n")
    doc.add_heading(lines[0] if lines else "Талдамалық анықтама", level=1)
    for line in lines[1:]:
        if not line.strip():
            continue
        head = line.split(". ", 1)
        if len(head) == 2 and head[0].isdigit() and head[1] in SECTION_TITLES:
            doc.add_heading(line, level=2)
        else:
            doc.add_paragraph(line)
    if calc_table and len(calc_table) > 1:
        doc.add_heading("Қосымша: есептеулер кестесі", level=2)
        t = doc.add_table(rows=1, cols=len(calc_table[0]))
        t.style = "Table Grid"
        for i, h in enumerate(calc_table[0]):
            t.rows[0].cells[i].text = to_str(h)
        for r in calc_table[1:]:
            cells = t.add_row().cells
            for i in range(len(calc_table[0])):
                cells[i].text = to_str(r[i]) if i < len(r) else ""
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def to_csv_bytes(matrix) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf, delimiter=";", lineterminator="\r\n")
    for r in matrix:
        w.writerow([to_str(v) for v in r])
    return ("﻿" + buf.getvalue()).encode("utf-8")


